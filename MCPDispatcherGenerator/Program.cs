// Program.cs  (Console app)
// Generates C# handler stubs + dispatcher switch from McpToolsetDefinition.json
//
// Usage:
//   dotnet run -- path/to/McpToolsetDefinition.json > GeneratedHandlers.cs
//
// Notes:
// - This is a SKETCH that is robust-ish against missing fields.
// - Adjust the JSON property names if your schema differs (e.g. "inputSchema" vs "x-inputSchema").
// - The generator outputs:
//     * a switch(method) dispatcher snippet
//     * one handler method per tool that parses params (very basic) and returns JsonNode stub
//
// Requires: <LangVersion>latest</LangVersion>

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
namespace MCPDispatcherGenerator
